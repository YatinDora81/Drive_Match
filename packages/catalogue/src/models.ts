import type { BodyType, Feature, FuelType } from "@repo/contracts";

export type Tier = "budget" | "mass" | "premium" | "luxury";

export type TrimLevel = "base" | "mid" | "top";

export type Gearbox = "MT" | "AT" | "AMT" | "CVT" | "DCT" | "DSG" | "IVT" | "e-CVT";

export type GearboxOption =
  Gearbox | { box: Gearbox; years: readonly [number, number] };

export type Engine = {
  label: string;
  fuel: FuelType;
  cc: number | null;
  bhp: number;
  kmpl: number | null;
  rangeKm: number | null;
  batteryKwh: number | null;
  gearboxes: readonly GearboxOption[];
  band: readonly [number, number];
  years?: readonly [number, number];
};

export type ModelLine = {
  make: string;
  model: string;
  bodyType: BodyType;
  tier: Tier;
  seats: readonly number[];
  seatsByTrim?: Readonly<Record<string, readonly number[]>>;
  safetyRating: number | null;
  safetyBefore?: { year: number; rating: number | null };
  years: readonly [number, number];
  offSale?: readonly [number, number];
  trims: readonly string[];
  trimsBefore?: { year: number; trims: readonly string[] };
  automaticOnly?: readonly string[];
  baseAutomatic?: boolean;
  engines: readonly Engine[];
  never?: readonly Feature[];
  featureFrom?: Partial<Record<Feature, number>>;
  offRoad?: boolean;
  retention?: number;
  floor?: number;
  weight: number;
};

export const CATALOGUE_YEAR = 2025;

export const FIRST_MODEL_YEAR = 2015;

type Years = readonly [number, number] | undefined;

const from = (box: Gearbox, year: number): GearboxOption => ({
  box,
  years: [year, CATALOGUE_YEAR],
});

const until = (box: Gearbox, year: number): GearboxOption => ({
  box,
  years: [FIRST_MODEL_YEAR, year],
});

const combustion =
  (fuel: FuelType) =>
  (
    label: string,
    cc: number,
    bhp: number,
    kmpl: number,
    gearboxes: readonly GearboxOption[],
    band: readonly [number, number],
    years?: Years,
  ): Engine => ({
    label,
    fuel,
    cc,
    bhp,
    kmpl,
    rangeKm: null,
    batteryKwh: null,
    gearboxes,
    band,
    years,
  });

const petrol = combustion("PETROL");
const diesel = combustion("DIESEL");
const cng = combustion("CNG");
const hybrid = combustion("HYBRID");

const electric = (
  label: string,
  bhp: number,
  rangeKm: number,
  batteryKwh: number,
  band: readonly [number, number],
  years?: Years,
): Engine => ({
  label,
  fuel: "ELECTRIC",
  cc: null,
  bhp,
  kmpl: null,
  rangeKm,
  batteryKwh,
  gearboxes: [],
  band,
  years,
});

